/**
 * Translate a string into the selected language
 */
export const t = (text, lang) => {
  if (lang !== 'hi' || !text || typeof text !== 'string') return text;
  const trimmed = text.trim();
  if (HINDI_DICTIONARY[trimmed]) return HINDI_DICTIONARY[trimmed];
  const clean = trimmed.replace(/[\u2018\u2019]/g, "'").replace(/[\u201C\u201D]/g, '"').replace(/\s+/g, ' ').toLowerCase();
  if (LOWER_DICT[clean]) return LOWER_DICT[clean];
  return text;
};

/**
 * Dynamic DOM Node Translator
 * Scans visible text nodes, attributes, and attaches MutationObserver for continuous translation
 */
let domObserver = null;
let isTranslating = false;

export const applyLanguageToDOM = (targetLang) => {
  if (typeof document === 'undefined') return;

  document.documentElement.lang = targetLang === 'hi' ? 'hi' : 'en';

  if (targetLang !== 'hi') {
    // ENGLISH MODE: Disconnect observer & restore original English
    if (domObserver) {
      domObserver.disconnect();
      domObserver = null;
    }
    
    const restoreNode = (node) => {
      if (node.nodeType === Node.TEXT_NODE) {
        if (node._originalEn) {
          node.nodeValue = node._originalEn;
        } else {
          const val = node.nodeValue.trim();
          if (REVERSE_DICT[val]) {
            node.nodeValue = node.nodeValue.replace(val, REVERSE_DICT[val]);
          }
        }
      } else if (node.nodeType === Node.ELEMENT_NODE) {
        const tag = node.tagName.toLowerCase();
        if (['script', 'style', 'code', 'svg', 'path'].includes(tag)) return;
        if (node._originalPlaceholder) node.placeholder = node._originalPlaceholder;
        if (node._originalTitle) node.title = node._originalTitle;
        for (let child of node.childNodes) {
          restoreNode(child);
        }
      }
    };

    if (document.body) {
      restoreNode(document.body);
    }
    return;
  }

  // HINDI MODE: Translate text nodes
  const translateNode = (node) => {
    if (node.nodeType === Node.TEXT_NODE) {
      const raw = node.nodeValue;
      if (!raw || !raw.trim()) return;

      if (!node._originalEn) node._originalEn = raw;

      const leadingWs = (raw.match(/^\s*/) || [''])[0];
      const trailingWs = (raw.match(/\s*$/) || [''])[0];
      const trimmed = raw.trim();

      // 1. Direct match on trimmed text
      if (HINDI_DICTIONARY[trimmed]) {
        node.nodeValue = leadingWs + HINDI_DICTIONARY[trimmed] + trailingWs;
        return;
      }

      // 2. Normalized match (collapse whitespace and normalize smart quotes)
      const clean = trimmed.replace(/[\u2018\u2019]/g, "'").replace(/[\u201C\u201D]/g, '"').replace(/\s+/g, ' ');
      const cleanLower = clean.toLowerCase();
      if (LOWER_DICT[cleanLower]) {
        node.nodeValue = leadingWs + LOWER_DICT[cleanLower] + trailingWs;
        return;
      }

      // 3. Phrase pattern replacements
      let updated = raw;
      for (const [re, rep] of PHRASE_REPLACEMENTS) {
        if (re.test(updated)) {
          updated = updated.replace(re, rep);
        }
      }
      if (updated !== raw) {
        node.nodeValue = updated;
      }
    } else if (node.nodeType === Node.ELEMENT_NODE) {
      const tag = node.tagName.toLowerCase();
      if (['script', 'style', 'code', 'svg', 'path'].includes(tag)) return;

      // Translate placeholders
      if (node.placeholder) {
        const pVal = node.placeholder.trim();
        const pClean = pVal.replace(/[\u2018\u2019]/g, "'").replace(/[\u201C\u201D]/g, '"').replace(/\s+/g, ' ').toLowerCase();
        const transP = HINDI_DICTIONARY[pVal] || LOWER_DICT[pClean];
        if (transP) {
          if (!node._originalPlaceholder) node._originalPlaceholder = node.placeholder;
          node.placeholder = transP;
        }
      }

      // Translate titles
      if (node.title) {
        const tVal = node.title.trim();
        const tClean = tVal.replace(/[\u2018\u2019]/g, "'").replace(/[\u201C\u201D]/g, '"').replace(/\s+/g, ' ').toLowerCase();
        const transT = HINDI_DICTIONARY[tVal] || LOWER_DICT[tClean];
        if (transT) {
          if (!node._originalTitle) node._originalTitle = node.title;
          node.title = transT;
        }
      }

      for (let child of node.childNodes) {
        translateNode(child);
      }
    }
  };

  if (document.body) {
    isTranslating = true;
    translateNode(document.body);
    isTranslating = false;
  }

  // Setup active characterData & childList observer so dynamic React re-renders stay in Hindi
  if (domObserver) {
    domObserver.disconnect();
    domObserver = null;
  }

  domObserver = new MutationObserver((mutations) => {
    if (isTranslating) return;
    isTranslating = true;
    try {
      for (const m of mutations) {
        if (m.type === 'childList') {
          m.addedNodes.forEach(node => translateNode(node));
        } else if (m.type === 'characterData' && m.target) {
          translateNode(m.target);
        }
      }
    } catch(e) {}
    isTranslating = false;
  });

  domObserver.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true
  });
};
