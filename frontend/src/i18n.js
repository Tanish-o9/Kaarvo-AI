export const applyLanguageToDOM = (targetLang) => {
  if (typeof document === 'undefined') return;

  document.documentElement.lang = targetLang === 'hi' ? 'hi' : 'en';

  const translateNode = (node) => {
    if (node.nodeType === Node.TEXT_NODE) {
      const val = node.nodeValue.trim();
      if (!val) return;

      if (targetLang === 'hi') {
        const trans = HINDI_DICTIONARY[val] || LOWER_DICT[val.toLowerCase()];
        if (trans && trans !== val) {
          if (!node._originalEn) node._originalEn = node.nodeValue;
          node.nodeValue = node.nodeValue.replace(val, trans);
        }
      } else {
        // Restore English
        if (node._originalEn) {
          node.nodeValue = node._originalEn;
        } else {
          const rev = REVERSE_DICT[val];
          if (rev) node.nodeValue = node.nodeValue.replace(val, rev);
        }
      }
    } else if (node.nodeType === Node.ELEMENT_NODE) {
      // Don't touch script/style/inputs value
      const tag = node.tagName.toLowerCase();
      if (['script', 'style', 'code', 'svg', 'path'].includes(tag)) return;

      // Translate placeholders
      if (node.placeholder) {
        const pVal = node.placeholder.trim();
        if (targetLang === 'hi') {
          const transP = HINDI_DICTIONARY[pVal] || LOWER_DICT[pVal.toLowerCase()];
          if (transP) {
            if (!node._originalPlaceholder) node._originalPlaceholder = node.placeholder;
            node.placeholder = transP;
          }
        } else if (node._originalPlaceholder) {
          node.placeholder = node._originalPlaceholder;
        }
      }

      // Translate title attribute
      if (node.title) {
        const tVal = node.title.trim();
        if (targetLang === 'hi') {
          const transT = HINDI_DICTIONARY[tVal] || LOWER_DICT[tVal.toLowerCase()];
          if (transT) {
            if (!node._originalTitle) node._originalTitle = node.title;
            node.title = transT;
          }
        } else if (node._originalTitle) {
          node.title = node._originalTitle;
        }
      }

      // Recurse children
      for (let child of node.childNodes) {
        translateNode(child);
      }
    }
  };

  // Perform pass on body
  if (document.body) {
    translateNode(document.body);
  }

  // Setup observer for dynamic modal / tab content
  if (domObserver) {
    domObserver.disconnect();
    domObserver = null;
  }

  if (targetLang === 'hi') {
    domObserver = new MutationObserver((mutations) => {
      for (const m of mutations) {
        m.addedNodes.forEach(node => translateNode(node));
      }
    });
    domObserver.observe(document.body, { childList: true, subtree: true });
  }
};
